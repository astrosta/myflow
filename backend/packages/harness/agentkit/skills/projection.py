"""Milvus active projection for user-private skills.

The collection is a materialized view, not a version index: one row per active
private skill, keyed by projection_key and carrying owner_user_id.  PostgreSQL
remains the authority; Milvus narrows the candidate set and every hit is
confirmed against the caller's active pointer before it becomes visible.

Retrieval is entirely server-side: the collection carries a BM25 sparse field
generated by a Milvus Function, and hybrid recall uses Milvus' RRFRanker.  The
client never tokenizes, scores BM25, or fuses rankings itself.

pymilvus is imported lazily so importing the catalog does not require the
optional Milvus client until the active projection is actually used.
"""

from __future__ import annotations

import asyncio
import json
import logging
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, Protocol

from agentkit.knowledge.config import MilvusConfig

logger = logging.getLogger(__name__)

ACTIVE_COLLECTION = "myflow_skills_active"

OUTPUT_FIELDS = [
    "pk",
    "scope",
    "owner_user_id",
    "skill_id",
    "version_id",
    "skill_version",
    "enabled",
    "name",
    "description",
    "package_sha256",
    "skill_md_sha256",
]

_QUERY_LIMIT = 16384
_SCOPES = frozenset({"private"})
_SCALAR_INDEX_FIELDS = ("scope", "owner_user_id", "enabled")
_CONTENT_FIELD = "content"
_VECTOR_FIELD = "embedding"
_SPARSE_FIELD = "sparse"

#: Milvus 700 = IndexNotExist.  Loading a collection without a vector index always
#: fails this way, so it is a repairable state, not a terminal one.
_MISSING_INDEX_HINTS = (
    "index not found",
    "index not exist",
    "index doesn't exist",
    "no vector index",
    "index hasn't been created",
)
#: Two workers may create the same index concurrently; the loser is told so.
_INDEX_EXISTS_HINTS = ("already exist", "duplicate index")


class ProjectionUnavailable(RuntimeError):
    """The active Milvus projection cannot be read or written."""


def _error_code(exc: BaseException) -> int | None:
    code = getattr(exc, "code", None)
    try:
        return int(code) if code is not None else None
    except (TypeError, ValueError):
        return None


def _is_missing_index_error(exc: BaseException) -> bool:
    """True when Milvus refused the call because the collection has no index."""
    text = str(exc).lower()
    if any(hint in text for hint in _MISSING_INDEX_HINTS):
        return True
    return _error_code(exc) == 700


def _is_index_exists_error(exc: BaseException) -> bool:
    text = str(exc).lower()
    return any(hint in text for hint in _INDEX_EXISTS_HINTS)


@dataclass(frozen=True, slots=True)
class ProjectionRow:
    """One active private skill row."""

    projection_key: str
    scope: str
    owner_user_id: str | None
    skill_id: str
    version_id: str
    skill_version: str
    enabled: bool
    name: str
    description: str
    package_sha256: str
    skill_md_sha256: str
    embedding: Sequence[float]
    #: BM25 text indexed by Milvus (name + description + skill body).  The
    #: Milvus BM25 Function turns it into the sparse vector on insert.
    content: str = ""


@dataclass(frozen=True, slots=True)
class ProjectionHit:
    """A vector hit, before PostgreSQL confirms the active pointer."""

    projection_key: str
    scope: str
    owner_user_id: str | None
    skill_id: str
    version_id: str
    score: float


class SkillProjectionStore(Protocol):
    async def ensure_collection(self, dimensions: int) -> None: ...

    async def upsert_active(self, row: ProjectionRow) -> None: ...

    async def delete_active(self, projection_key: str) -> None: ...

    async def search(
        self,
        *,
        user_id: str,
        vector: Sequence[float],
        limit: int,
    ) -> list[ProjectionHit]: ...

    async def keyword_search(
        self,
        *,
        user_id: str,
        query: str,
        limit: int,
    ) -> list[ProjectionHit]: ...

    async def hybrid_search(
        self,
        *,
        user_id: str,
        vector: Sequence[float],
        keyword_query: str,
        limit: int,
        rrf_k: int = 60,
    ) -> list[ProjectionHit]: ...

    async def scan_projection_keys(self, *, limit: int) -> tuple[list[str], bool]: ...

    async def aclose(self) -> None: ...


class MilvusSkillProjection:
    """Milvus implementation of the active skill projection."""

    def __init__(
        self,
        config: MilvusConfig,
        *,
        dimensions: int,
        client: Any | None = None,
        analyzer: str = "chinese",
        bm25_k1: float = 1.2,
        bm25_b: float = 0.75,
    ) -> None:
        self._dimensions = int(dimensions)
        if self._dimensions <= 0:
            raise ValueError("dimensions must be positive")
        self._config = config
        self._analyzer = analyzer
        self._bm25_k1 = float(bm25_k1)
        self._bm25_b = float(bm25_b)
        # MilvusConfig's own default belongs to the knowledge collection.  The
        # projection uses its active collection unless the caller configured one.
        self._collection = (
            config.collection
            if "collection" in config.model_fields_set
            else ACTIVE_COLLECTION
        )
        # Bounded Staleness is the default; an explicit deployment setting still wins.
        self._consistency_level = (
            config.consistency_level
            if "consistency_level" in config.model_fields_set
            else "Bounded"
        )
        self._client = client

    def _client_instance(self):
        if self._client is None:
            try:
                from pymilvus import MilvusClient
            except ImportError as exc:
                raise ProjectionUnavailable(
                    "pymilvus is not installed; install the skills extra"
                ) from exc
            kwargs: dict[str, Any] = {"uri": self._config.uri}
            if self._config.token:
                kwargs["token"] = self._config.token
            if self._config.db_name:
                kwargs["db_name"] = self._config.db_name
            self._client = MilvusClient(**kwargs)
        return self._client

    async def ensure_collection(self, dimensions: int) -> None:
        value = int(dimensions)
        if value <= 0:
            raise ValueError("dimensions must be positive")
        self._dimensions = value
        await asyncio.to_thread(self._ensure_collection_sync)

    async def upsert_active(self, row: ProjectionRow) -> None:
        record = self._record(row)
        await asyncio.to_thread(self._upsert_sync, record)

    async def delete_active(self, projection_key: str) -> None:
        if not projection_key:
            raise ValueError("projection_key must not be blank")
        expression = f"pk == {json.dumps(projection_key)}"
        await asyncio.to_thread(self._delete_sync, expression)

    async def search(
        self,
        *,
        user_id: str,
        vector: Sequence[float],
        limit: int,
    ) -> list[ProjectionHit]:
        values = self._validate_vector(vector)
        if int(limit) <= 0:
            raise ValueError("limit must be positive")
        expression = self._filter(user_id)
        rows = await asyncio.to_thread(
            self._search_sync, expression, values, int(limit)
        )
        return self._to_hits(rows)

    async def keyword_search(
        self,
        *,
        user_id: str,
        query: str,
        limit: int,
    ) -> list[ProjectionHit]:
        keyword = query.strip()
        if not keyword:
            raise ValueError("keyword query must not be empty")
        if int(limit) <= 0:
            raise ValueError("limit must be positive")
        rows = await asyncio.to_thread(
            self._keyword_search_sync,
            self._filter(user_id),
            keyword,
            int(limit),
        )
        return self._to_hits(rows)

    async def hybrid_search(
        self,
        *,
        user_id: str,
        vector: Sequence[float],
        keyword_query: str,
        limit: int,
        rrf_k: int = 60,
    ) -> list[ProjectionHit]:
        """Dense + BM25 recall fused server-side by Milvus RRFRanker."""
        values = self._validate_vector(vector)
        keyword = keyword_query.strip()
        if not keyword:
            raise ValueError("keyword query must not be empty")
        if int(limit) <= 0:
            raise ValueError("limit must be positive")
        if int(rrf_k) <= 0:
            raise ValueError("rrf_k must be positive")
        rows = await asyncio.to_thread(
            self._hybrid_search_sync,
            self._filter(user_id),
            values,
            keyword,
            int(limit),
            int(rrf_k),
        )
        return self._to_hits(rows)

    def _validate_vector(self, vector: Sequence[float]) -> list[float]:
        values = list(vector)
        if len(values) != self._dimensions:
            raise ValueError(
                f"query vector dimension mismatch: expected {self._dimensions}, "
                f"got {len(values)}"
            )
        return values

    async def scan_projection_keys(self, *, limit: int) -> tuple[list[str], bool]:
        """Stream the projection primary keys, stopping after limit.

        Returns (keys, truncated).  A single bounded query silently truncates at
        16384 rows and every row beyond the window then looks missing, so the
        integrity sweep walks the collection with a query iterator instead.
        """
        return await asyncio.to_thread(self._scan_keys_sync, int(limit))

    async def aclose(self) -> None:
        client = self._client
        if client is None:
            return
        self._client = None
        close = getattr(client, "close", None)
        if callable(close):
            await asyncio.to_thread(close)

    # ------------------------------------------------------------------
    # synchronous Milvus operations
    # ------------------------------------------------------------------

    def _upsert_sync(self, record: dict[str, Any]) -> None:
        client = self._client_instance()
        try:
            self._ensure_collection_sync(client)
            client.upsert(collection_name=self._collection, data=[record])
        except ProjectionUnavailable:
            raise
        except Exception as exc:
            raise ProjectionUnavailable(
                f"Milvus projection upsert failed: {type(exc).__name__}"
            ) from exc

    def _delete_sync(self, expression: str) -> None:
        client = self._client_instance()
        try:
            if not client.has_collection(self._collection):
                return
            client.delete(collection_name=self._collection, filter=expression)
        except ProjectionUnavailable:
            raise
        except Exception as exc:
            raise ProjectionUnavailable(
                f"Milvus projection delete failed: {type(exc).__name__}"
            ) from exc

    def _search_sync(
        self, expression: str, vector: list[float], limit: int
    ) -> list[dict]:
        client = self._client_instance()
        try:
            self._ensure_collection_sync(client)
            result = client.search(
                collection_name=self._collection,
                data=[vector],
                anns_field="embedding",
                search_params={
                    "metric_type": self._config.metric_type,
                    "params": {},
                },
                limit=limit,
                filter=expression,
                output_fields=list(OUTPUT_FIELDS),
                consistency_level=self._consistency_level,
            )
        except ProjectionUnavailable:
            raise
        except Exception as exc:
            raise ProjectionUnavailable(
                f"Milvus projection search failed: {type(exc).__name__}"
            ) from exc
        return self._first_rows(result)

    def _keyword_search_sync(
        self, expression: str, query: str, limit: int
    ) -> list[dict]:
        client = self._client_instance()
        try:
            self._ensure_collection_sync(client)
            result = client.search(
                collection_name=self._collection,
                data=[query],
                anns_field=_SPARSE_FIELD,
                search_params={"metric_type": "BM25", "params": {}},
                limit=limit,
                filter=expression,
                output_fields=list(OUTPUT_FIELDS),
                consistency_level=self._consistency_level,
            )
        except ProjectionUnavailable:
            raise
        except Exception as exc:
            raise ProjectionUnavailable(
                f"Milvus projection keyword search failed: {type(exc).__name__}"
            ) from exc
        return self._first_rows(result)

    def _hybrid_search_sync(
        self,
        expression: str,
        vector: list[float],
        query: str,
        limit: int,
        rrf_k: int,
    ) -> list[dict]:
        client = self._client_instance()
        try:
            from pymilvus import AnnSearchRequest, RRFRanker
        except ImportError as exc:
            raise ProjectionUnavailable(
                "pymilvus has no hybrid search; install a 2.5+ client"
            ) from exc
        try:
            self._ensure_collection_sync(client)
            # MilvusClient.hybrid_search has no top-level filter: dropping it into
            # kwargs silently disables tenant isolation, so it goes on both channels.
            requests = [
                AnnSearchRequest(
                    data=[vector],
                    anns_field=_VECTOR_FIELD,
                    param={
                        "metric_type": self._config.metric_type,
                        "params": {},
                    },
                    limit=limit,
                    expr=expression,
                ),
                AnnSearchRequest(
                    data=[query],
                    anns_field=_SPARSE_FIELD,
                    param={"metric_type": "BM25", "params": {}},
                    limit=limit,
                    expr=expression,
                ),
            ]
            result = client.hybrid_search(
                collection_name=self._collection,
                reqs=requests,
                ranker=RRFRanker(rrf_k),
                limit=limit,
                output_fields=list(OUTPUT_FIELDS),
                consistency_level=self._consistency_level,
            )
        except ProjectionUnavailable:
            raise
        except Exception as exc:
            raise ProjectionUnavailable(
                f"Milvus projection hybrid search failed: {type(exc).__name__}"
            ) from exc
        return self._first_rows(result)

    def _scan_keys_sync(self, limit: int) -> tuple[list[str], bool]:
        if limit <= 0:
            return [], False
        client = self._client_instance()
        self._ensure_collection_sync(client)
        make_iterator = getattr(client, "query_iterator", None)
        if not callable(make_iterator):
            # 老客户端没有 iterator：退回单次 query，并且如实报告可能被截断。
            try:
                rows = client.query(
                    collection_name=self._collection,
                    filter="",
                    output_fields=["pk"],
                    limit=min(limit, _QUERY_LIMIT),
                )
            except Exception as exc:  # noqa: BLE001 - mapped to the projection error
                raise ProjectionUnavailable(
                    f"Milvus projection query failed: {type(exc).__name__}"
                ) from exc
            keys = [str(row["pk"]) for row in (rows or []) if isinstance(row, dict) and row.get("pk")]
            truncated = len(keys) >= min(limit, _QUERY_LIMIT)
            return keys[:limit], truncated
        try:
            iterator = make_iterator(
                collection_name=self._collection,
                batch_size=min(1000, limit),
                limit=-1,
                filter="",
                output_fields=["pk"],
            )
        except Exception as exc:  # noqa: BLE001 - mapped to the projection error
            raise ProjectionUnavailable(
                f"Milvus projection query failed: {type(exc).__name__}"
            ) from exc
        keys: list[str] = []
        try:
            while True:
                batch = iterator.next()
                if not batch:
                    break
                for row in batch:
                    if isinstance(row, dict) and row.get("pk"):
                        keys.append(str(row["pk"]))
                        if len(keys) >= limit:
                            return keys, True
        finally:
            close = getattr(iterator, "close", None)
            if callable(close):
                try:
                    close()
                except Exception:  # noqa: BLE001 - closing is best effort
                    logger.debug("Could not close Milvus iterator", exc_info=True)
        return keys, False

    def _ensure_collection_sync(self, client: Any | None = None) -> None:
        """Converge to "exists + right dimensions + indexed + loaded".

        "The collection exists" is not the same as "the collection is usable": a
        creation that dies between create_collection and create_index, or an index
        dropped by hand, leaves a collection whose load fails with 700 index not
        found.  Assuming it was ready made every retry fail the same way, so an
        existing collection is inspected and repaired instead of trusted.
        """
        client = client or self._client_instance()
        if not client.has_collection(self._collection):
            self._create_collection(client)
            return
        self._inspect_collection(client)
        missing = self._missing_search_indexes(client)
        if missing:
            logger.warning(
                "Milvus skill projection %s is missing search indexes %s; "
                "creating them before loading",
                self._collection,
                ", ".join(missing),
            )
            self._create_indexes(client, fields=missing)
        self._load(client)

    def _inspect_collection(self, client: Any) -> None:
        describe = getattr(client, "describe_collection", None)
        if not callable(describe):
            return
        try:
            description = describe(self._collection)
        except Exception:
            logger.debug("Could not inspect Milvus skill projection schema", exc_info=True)
            return
        fields = description.get("fields", []) if isinstance(description, dict) else []
        names = {field.get("name") for field in fields if isinstance(field, dict)}
        if names and _SPARSE_FIELD not in names:
            raise ProjectionUnavailable(
                "Milvus skill projection has no BM25 sparse field; stop the gateway, "
                "run \"python -m backend.scripts.reset_knowledge_milvus "
                "--collection myflow_skills_active --apply\", and re-project active "
                "skills (the old collection is not compatible)"
            )
        for field in fields:
            if not isinstance(field, dict) or field.get("name") != "embedding":
                continue
            params = field.get("params") or {}
            dim = params.get("dim") if isinstance(params, dict) else None
            if dim and int(dim) != self._dimensions:
                raise ProjectionUnavailable(
                    "Milvus skill projection dimension mismatch: "
                    f"expected {self._dimensions}, got {dim}"
                )

    def _load(self, client: Any) -> None:
        """Load the collection, repairing a missing index exactly once."""
        load = getattr(client, "load_collection", None)
        if not callable(load):
            return
        try:
            load(self._collection)
            return
        except Exception as exc:  # noqa: BLE001 - only the index case is repairable
            if not _is_missing_index_error(exc):
                raise ProjectionUnavailable(
                    f"Milvus skill projection load failed: {type(exc).__name__}"
                ) from exc
            logger.warning(
                "Milvus skill projection %s refused to load without an index; "
                "creating the index and retrying once",
                self._collection,
            )
        # Covers an index that only just became visible and a collection that lost
        # its index between the check above and this load.  A second failure is a
        # real failure: the outbox backs off and tries again later.
        self._create_indexes(client)
        try:
            load(self._collection)
        except Exception as exc:  # noqa: BLE001 - mapped to the projection error
            raise ProjectionUnavailable(
                f"Milvus skill projection load failed: {type(exc).__name__}"
            ) from exc

    def _missing_search_indexes(self, client: Any) -> list[str]:
        """Which required search fields have no index yet.

        Unknown answers return an empty list: a client without introspection
        should not trigger a blind create_index on every call, and the load path
        repairs a genuinely missing index anyway.  Milvus names an index after
        its field by default, so both the index name and describe_index count as
        evidence.
        """
        required = [_VECTOR_FIELD, _SPARSE_FIELD]
        list_indexes = getattr(client, "list_indexes", None)
        if not callable(list_indexes):
            return []
        try:
            names = [str(name) for name in (list_indexes(self._collection) or [])]
        except Exception:  # noqa: BLE001 - introspection is advisory only
            logger.debug(
                "Could not list Milvus skill projection indexes", exc_info=True
            )
            return []
        if not names:
            return required
        indexed = {name for name in names if name in required}
        describe = getattr(client, "describe_index", None)
        if callable(describe):
            for name in names:
                if name in indexed:
                    continue
                try:
                    described = describe(self._collection, name)
                except Exception:  # noqa: BLE001 - try the next index name
                    logger.debug(
                        "Could not describe Milvus index %s", name, exc_info=True
                    )
                    continue
                if isinstance(described, dict):
                    field_name = described.get("field_name")
                    if field_name in required:
                        indexed.add(str(field_name))
        return [field for field in required if field not in indexed]

    def _create_indexes(
        self, client: Any, *, fields: Sequence[str] | None = None
    ) -> None:
        target = list(fields) if fields is not None else [_VECTOR_FIELD, _SPARSE_FIELD]
        try:
            index_params = client.prepare_index_params()
            if _VECTOR_FIELD in target:
                index_params.add_index(
                    field_name=_VECTOR_FIELD,
                    index_type=self._config.index_type,
                    metric_type=self._config.metric_type,
                    params={},
                )
            if _SPARSE_FIELD in target:
                index_params.add_index(
                    field_name=_SPARSE_FIELD,
                    index_type="SPARSE_INVERTED_INDEX",
                    metric_type="BM25",
                    params={
                        "bm25_k1": self._bm25_k1,
                        "bm25_b": self._bm25_b,
                    },
                )
            if fields is None or (
                _VECTOR_FIELD in target and _SPARSE_FIELD in target
            ):
                for field_name in _SCALAR_INDEX_FIELDS:
                    index_params.add_index(
                        field_name=field_name,
                        index_type="INVERTED",
                    )
            # Milvus refuses to build an index on a loaded collection.
            self._release(client)
            try:
                client.create_index(
                    collection_name=self._collection, index_params=index_params
                )
            except Exception as exc:  # noqa: BLE001 - another worker may have won
                if not _is_index_exists_error(exc):
                    raise
                logger.info(
                    "Milvus skill projection %s already has this index; continuing",
                    self._collection,
                )
        except ProjectionUnavailable:
            raise
        except Exception as exc:
            raise ProjectionUnavailable(
                "Milvus skill projection index creation failed: "
                f"{type(exc).__name__}"
            ) from exc

    def _release(self, client: Any) -> None:
        release = getattr(client, "release_collection", None)
        if not callable(release):
            return
        try:
            release(self._collection)
        except Exception:  # noqa: BLE001 - "not loaded" is the normal case here
            logger.debug(
                "Could not release Milvus skill projection %s", self._collection,
                exc_info=True,
            )

    def _create_collection(self, client: Any) -> None:
        try:
            from pymilvus import DataType, Function, FunctionType
        except ImportError as exc:
            raise ProjectionUnavailable(
                "pymilvus is not installed; install the skills extra"
            ) from exc
        created = False
        try:
            schema = client.create_schema(auto_id=False, enable_dynamic_field=False)
            schema.add_field("pk", DataType.VARCHAR, is_primary=True, max_length=255)
            schema.add_field("scope", DataType.VARCHAR, max_length=32)
            schema.add_field("owner_user_id", DataType.VARCHAR, max_length=255)
            schema.add_field("skill_id", DataType.VARCHAR, max_length=255)
            schema.add_field("version_id", DataType.VARCHAR, max_length=255)
            schema.add_field("skill_version", DataType.VARCHAR, max_length=255)
            schema.add_field("enabled", DataType.BOOL)
            schema.add_field("name", DataType.VARCHAR, max_length=1024)
            schema.add_field("description", DataType.VARCHAR, max_length=65535)
            schema.add_field("package_sha256", DataType.VARCHAR, max_length=128)
            schema.add_field("skill_md_sha256", DataType.VARCHAR, max_length=128)
            schema.add_field(
                _CONTENT_FIELD,
                DataType.VARCHAR,
                max_length=65535,
                enable_analyzer=True,
                analyzer_params={"type": self._analyzer},
            )
            schema.add_field(_SPARSE_FIELD, DataType.SPARSE_FLOAT_VECTOR)
            schema.add_field("embedding", DataType.FLOAT_VECTOR, dim=self._dimensions)
            schema.add_function(
                Function(
                    name="skills_bm25",
                    input_field_names=[_CONTENT_FIELD],
                    output_field_names=[_SPARSE_FIELD],
                    function_type=FunctionType.BM25,
                )
            )

            # Indexes are created after the collection, never through
            # create_collection(index_params=...): a failure between the two steps
            # used to leave a collection that could never be loaded, and every
            # retry then took the "already exists" path straight into 700.
            client.create_collection(
                collection_name=self._collection,
                schema=schema,
                consistency_level=self._consistency_level,
            )
            created = True
            self._create_indexes(client)
            self._load(client)
        except ProjectionUnavailable:
            self._discard_half_created(client, created=created)
            raise
        except Exception as exc:
            self._discard_half_created(client, created=created)
            raise ProjectionUnavailable(
                f"Milvus skill projection creation failed: {type(exc).__name__}"
            ) from exc

    def _discard_half_created(self, client: Any, *, created: bool) -> None:
        """Drop the collection this call just created so no ghost is left behind."""
        if not created:
            return
        drop = getattr(client, "drop_collection", None)
        if not callable(drop):
            return
        try:
            drop(self._collection)
            logger.warning(
                "Dropped half-created Milvus skill projection %s so the next "
                "retry starts clean",
                self._collection,
            )
        except Exception:  # noqa: BLE001 - cleanup is best effort
            logger.warning(
                "Could not drop half-created Milvus skill projection %s",
                self._collection,
                exc_info=True,
            )

    # ------------------------------------------------------------------
    # records, filters, and hits
    # ------------------------------------------------------------------

    def _record(self, row: ProjectionRow) -> dict[str, Any]:
        if row.scope not in _SCOPES:
            raise ValueError(f"unsupported projection scope: {row.scope!r}")
        if not row.projection_key or not row.skill_id or not row.version_id:
            raise ValueError("projection key, skill id, and version id must not be blank")
        values = list(row.embedding)
        if len(values) != self._dimensions:
            raise ValueError(
                f"embedding dimension mismatch: expected {self._dimensions}, "
                f"got {len(values)}"
            )
        return {
            "pk": row.projection_key,
            "scope": row.scope,
            "owner_user_id": row.owner_user_id or "",
            "skill_id": row.skill_id,
            "version_id": row.version_id,
            "skill_version": row.skill_version,
            "enabled": bool(row.enabled),
            "name": row.name,
            "description": row.description,
            "package_sha256": row.package_sha256,
            "skill_md_sha256": row.skill_md_sha256,
            "content": row.content[:65535],
            "embedding": values,
        }

    @staticmethod
    def _filter(user_id: str) -> str:
        return (
            'scope == "private" and enabled == true and owner_user_id == '
            f"{json.dumps(user_id)}"
        )

    @staticmethod
    def _first_rows(result: Any) -> list[dict]:
        if isinstance(result, dict):
            result = result.get("data") or []
        if not result:
            return []
        first = result[0]
        return list(first) if isinstance(first, list) else list(result)

    @staticmethod
    def _to_hits(rows: list[dict]) -> list[ProjectionHit]:
        hits: list[ProjectionHit] = []
        for row in rows:
            if not isinstance(row, dict):
                continue
            entity = row.get("entity")
            if not isinstance(entity, dict):
                entity = row
            projection_key = str(
                entity.get("pk") or entity.get("projection_key") or row.get("id") or ""
            )
            if not projection_key:
                continue
            owner_user_id = str(entity.get("owner_user_id") or "") or None
            distance = row.get("distance", row.get("score", 0.0))
            try:
                score = float(distance) if distance is not None else 0.0
            except (TypeError, ValueError):
                score = 0.0
            hits.append(
                ProjectionHit(
                    projection_key=projection_key,
                    scope=str(entity.get("scope") or ""),
                    owner_user_id=owner_user_id,
                    skill_id=str(entity.get("skill_id") or ""),
                    version_id=str(entity.get("version_id") or ""),
                    score=score,
                )
            )
        return hits
