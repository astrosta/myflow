"""Memory management surface: list, inspect, edit and delete OpenViking memories.

The page is a protocol proxy, not a second memory store: every method takes the
caller's OpenViking user id and calls the user-scoped client directly. Nothing is
cached or copied into MyFlow's database.

Layout facts this module relies on (OpenViking 0.4.x):

* A memory is a Markdown **file** under `viking://user/<ov>/memories/<type>/...`.
* `.abstract.md` / `.overview.md` are **directory-level** sidecars (L0/L1). They
  are generated by OpenViking's semantic pipeline and are never editable here.
* The list uses a query-less `find` with a metadata filter (OpenViking's
  "filter-only" lookup) so each row carries the record's `abstract`; `ls` only
  exposes directory abstracts, which is why it is not used for the list.
"""

from __future__ import annotations

import hashlib
import logging
import re
from dataclasses import dataclass, field
from typing import Any, Protocol
from urllib.parse import unquote, urlsplit

logger = logging.getLogger(__name__)

#: The six automatic memory types the management page exposes. `tools` /
#: `skills` stay on the OpenViking Studio/CLI operations surface.
MEMORY_LIBRARY_TYPES: tuple[str, ...] = (
    "preferences",
    "entities",
    "events",
    "cases",
    "trajectories",
    "experiences",
)

MEMORY_TYPE_LABELS: dict[str, str] = {
    "preferences": "偏好",
    "entities": "实体",
    "events": "事件",
    "cases": "案例",
    "trajectories": "轨迹",
    "experiences": "经验",
}

MAX_LIST_LIMIT = 200
MAX_ABSTRACT_CHARS = 500
MAX_CONTENT_CHARS = 200_000
SIDECAR_NAMES = frozenset({".abstract.md", ".overview.md"})
DENIED_SEGMENTS = frozenset({"peers", "sessions", "privacy", "rules"})

_HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*$")
_LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
_MEMORY_ROOT = "memories"


class InvalidMemoryURI(ValueError):
    """The caller supplied a URI outside the manageable memory namespace."""


class MemoryItemNotFound(RuntimeError):
    """The memory file does not exist (or was deleted concurrently)."""


class MemoryWriteConflict(RuntimeError):
    """The stored content changed since the caller read it."""

    def __init__(self, current_sha256: str) -> None:
        super().__init__("memory changed since it was read")
        self.current_sha256 = current_sha256


class MemoryUnavailable(RuntimeError):
    """OpenViking is disabled, not initialized, or failed the call."""


class MemoryLibraryClient(Protocol):
    async def find(self, **kwargs: Any) -> dict[str, Any]: ...

    async def overview(self, uri: str) -> str: ...

    async def read(self, uri: str) -> str: ...

    async def ls(self, uri: str, **kwargs: Any) -> list[dict[str, Any]]: ...

    async def write(
        self,
        uri: str,
        content: str,
        *,
        mode: str = "replace",
        options: dict[str, Any] | None = None,
    ) -> dict[str, Any]: ...

    async def rm(self, uri: str, *, recursive: bool = False) -> None: ...


class MemoryLibraryResolver(Protocol):
    async def client_for(self, ov_user: str) -> MemoryLibraryClient: ...


@dataclass(frozen=True, slots=True)
class MemoryURI:
    uri: str
    folder: str
    name: str
    memory_type: str


@dataclass(frozen=True, slots=True)
class MemoryItem:
    uri: str
    name: str
    folder: str
    memory_type: str
    abstract: str
    abstract_truncated: bool
    updated_at: str


@dataclass(frozen=True, slots=True)
class TocEntry:
    kind: str  # "heading" | "link"
    title: str
    depth: int
    uri: str | None = None

    @property
    def navigable(self) -> bool:
        return self.kind == "link" and bool(self.uri)


@dataclass(frozen=True, slots=True)
class MemoryDetail:
    uri: str
    folder: str
    memory_type: str
    name: str
    overview: str
    toc: tuple[TocEntry, ...] = ()
    overview_missing: bool = False


@dataclass(frozen=True, slots=True)
class MemoryContent:
    uri: str
    content: str
    sha256: str
    size_bytes: int


@dataclass(frozen=True, slots=True)
class MemoryListPage:
    items: tuple[MemoryItem, ...] = ()
    has_more: bool = False
    limit: int = 50


def memory_type_label(memory_type: str) -> str:
    return MEMORY_TYPE_LABELS[memory_type]


def resolve_memory_uri(ov_user: str, uri: str) -> MemoryURI:
    """Validate an absolute user-memory file URI and split it into parts."""

    if not isinstance(uri, str) or not uri.strip():
        raise InvalidMemoryURI("uri is required")
    text = uri.strip()
    if "~" in text:
        raise InvalidMemoryURI("home alias is not allowed")
    parsed = urlsplit(text)
    if parsed.scheme != "viking" or parsed.netloc != "user":
        raise InvalidMemoryURI("absolute viking://user URI required")
    segments = [segment for segment in unquote(parsed.path).split("/") if segment]
    if not segments or segments[0] != ov_user:
        raise InvalidMemoryURI("URI is outside the current user memory namespace")
    if len(segments) < 4 or segments[1] != _MEMORY_ROOT:
        raise InvalidMemoryURI("URI must point inside memories/<type>/")
    memory_type = segments[2]
    if memory_type not in MEMORY_LIBRARY_TYPES:
        raise InvalidMemoryURI(f"unsupported memory type: {memory_type}")
    tail = segments[3:]
    if any(segment == ".." for segment in tail):
        raise InvalidMemoryURI("path traversal is not allowed")
    if any(segment in DENIED_SEGMENTS for segment in tail):
        raise InvalidMemoryURI("managed namespace is not manageable")
    if any(segment.startswith(".") for segment in tail):
        raise InvalidMemoryURI(".abstract.md / .overview.md and hidden files are read-only")
    name = tail[-1]
    if not name.endswith(".md"):
        raise InvalidMemoryURI("only Markdown memory files are manageable")
    if name in SIDECAR_NAMES:
        raise InvalidMemoryURI("memory sidecars are read-only")
    base = "viking://user/" + "/".join([ov_user, _MEMORY_ROOT, memory_type])
    folder = base + ("/" + "/".join(tail[:-1]) if len(tail) > 1 else "")
    return MemoryURI(
        uri=base + "/" + "/".join(tail),
        folder=folder,
        name=name,
        memory_type=memory_type,
    )


def parse_overview_toc(overview: str, *, folder: str) -> tuple[TocEntry, ...]:
    """Turn a `.overview.md` body into headings plus navigable sibling links."""

    entries: list[TocEntry] = []
    in_frontmatter = False
    seen_frontmatter = False
    for raw_line in (overview or "").splitlines():
        line = raw_line.strip()
        if line == "---":
            if not seen_frontmatter:
                in_frontmatter = True
                seen_frontmatter = True
                continue
            if in_frontmatter:
                in_frontmatter = False
                continue
        if in_frontmatter or not line:
            continue
        heading = _HEADING.match(line)
        if heading:
            depth = len(heading.group(1))
            entries.append(TocEntry("heading", heading.group(2), depth))
            continue
        for title, href in _LINK.findall(line):
            entries.append(
                TocEntry("link", title.strip(), 2, _resolve_toc_uri(href, folder=folder))
            )
    return tuple(entries)


def _resolve_toc_uri(href: str, *, folder: str) -> str | None:
    target = href.strip()
    if not target or target.startswith("#") or "://" in target:
        return None
    decoded = unquote(target)
    if decoded.startswith("./"):
        decoded = decoded[2:]
    if decoded.startswith("/") or ".." in decoded.split("/"):
        return None
    name = decoded.rsplit("/", 1)[-1]
    if not name.endswith(".md") or name.startswith("."):
        return None
    return folder.rstrip("/") + "/" + name


class MemoryLibraryService:
    """Protocol adapter behind the memory management endpoints."""

    def __init__(self, resolver: MemoryLibraryResolver) -> None:
        self._resolver = resolver

    async def list_items(
        self, ov_user: str, memory_type: str, *, limit: int = 50
    ) -> MemoryListPage:
        if memory_type not in MEMORY_LIBRARY_TYPES:
            raise InvalidMemoryURI(f"unsupported memory type: {memory_type}")
        bounded = max(1, min(int(limit), MAX_LIST_LIMIT))
        client = await self._client(ov_user)
        try:
            result = await client.find(
                query="",
                target_uri=[self._type_dir(ov_user, memory_type)],
                limit=bounded + 1,
                options={
                    "context_type": ["memory"],
                    "level": [2],
                    "read_content": False,
                    "filter": {
                        "op": "must",
                        "field": "context_type",
                        "conds": ["memory"],
                    },
                },
            )
        except Exception as exc:  # noqa: BLE001 - protocol boundary
            raise _translate(exc) from exc
        records = result.get("memories") if isinstance(result, dict) else None
        items: list[MemoryItem] = []
        for record in records or []:
            if not isinstance(record, dict):
                continue
            raw_uri = str(record.get("uri") or "")
            try:
                parsed = resolve_memory_uri(ov_user, raw_uri)
            except InvalidMemoryURI:
                continue
            if parsed.memory_type != memory_type:
                continue
            abstract = str(record.get("abstract") or "").strip()
            truncated = len(abstract) > MAX_ABSTRACT_CHARS
            items.append(
                MemoryItem(
                    uri=parsed.uri,
                    name=parsed.name,
                    folder=parsed.folder,
                    memory_type=parsed.memory_type,
                    abstract=abstract[:MAX_ABSTRACT_CHARS],
                    abstract_truncated=truncated,
                    updated_at=str(
                        record.get("updated_at")
                        or record.get("modified_at")
                        or record.get("modTime")
                        or ""
                    ),
                )
            )
        items.sort(key=lambda item: item.uri)
        return MemoryListPage(
            items=tuple(items[:bounded]),
            has_more=len(items) > bounded,
            limit=bounded,
        )

    async def detail(self, ov_user: str, uri: str) -> MemoryDetail:
        parsed = resolve_memory_uri(ov_user, uri)
        client = await self._client(ov_user)
        overview = ""
        try:
            overview = await client.overview(parsed.folder)
        except Exception:  # noqa: BLE001 - a missing sidecar is a degraded state
            logger.debug("memory overview missing for %s", parsed.folder, exc_info=True)
        toc = parse_overview_toc(overview, folder=parsed.folder)
        overview_missing = not any(entry.kind == "link" for entry in toc)
        if overview_missing:
            toc = await self._ls_toc(client, parsed.folder)
        return MemoryDetail(
            uri=parsed.uri,
            folder=parsed.folder,
            memory_type=parsed.memory_type,
            name=parsed.name,
            overview=overview,
            toc=toc,
            overview_missing=overview_missing,
        )

    async def read_content(self, ov_user: str, uri: str) -> MemoryContent:
        parsed = resolve_memory_uri(ov_user, uri)
        client = await self._client(ov_user)
        try:
            content = await client.read(parsed.uri)
        except Exception as exc:  # noqa: BLE001 - protocol boundary
            raise _translate(exc) from exc
        return _content(parsed.uri, content)

    async def update_content(
        self,
        ov_user: str,
        uri: str,
        content: str,
        *,
        expected_sha256: str | None,
    ) -> MemoryContent:
        parsed = resolve_memory_uri(ov_user, uri)
        if not isinstance(content, str) or not content.strip():
            raise ValueError("content must not be empty")
        if len(content) > MAX_CONTENT_CHARS:
            raise ValueError(f"content must be at most {MAX_CONTENT_CHARS} characters")
        client = await self._client(ov_user)
        try:
            current = await client.read(parsed.uri)
        except Exception as exc:  # noqa: BLE001
            raise _translate(exc) from exc
        current_sha = _sha256(current)
        if expected_sha256 and expected_sha256 != current_sha:
            raise MemoryWriteConflict(current_sha)
        try:
            await client.write(
                parsed.uri,
                content,
                mode="replace",
                options={"edit_source": "manual"},
            )
        except Exception as exc:  # noqa: BLE001
            raise _translate(exc) from exc
        return _content(parsed.uri, content)

    async def delete_item(self, ov_user: str, uri: str) -> None:
        parsed = resolve_memory_uri(ov_user, uri)
        client = await self._client(ov_user)
        try:
            await client.read(parsed.uri)
        except Exception as exc:  # noqa: BLE001
            raise _translate(exc) from exc
        try:
            await client.rm(parsed.uri, recursive=False)
        except Exception as exc:  # noqa: BLE001
            raise _translate(exc) from exc

    async def _ls_toc(
        self, client: MemoryLibraryClient, folder: str
    ) -> tuple[TocEntry, ...]:
        try:
            entries = await client.ls(
                folder, include_abstract=False, include_overview=False
            )
        except Exception:  # noqa: BLE001 - fallback is best effort
            logger.debug("memory ls fallback failed for %s", folder, exc_info=True)
            return ()
        links: list[TocEntry] = []
        for entry in entries or []:
            if not isinstance(entry, dict) or entry.get("isDir"):
                continue
            name = str(entry.get("name") or "")
            if not name.endswith(".md") or name.startswith("."):
                continue
            links.append(TocEntry("link", name[: -len(".md")], 2, folder + "/" + name))
        links.sort(key=lambda item: item.title.lower())
        return tuple(links)

    async def _client(self, ov_user: str) -> MemoryLibraryClient:
        try:
            return await self._resolver.client_for(ov_user)
        except Exception as exc:  # noqa: BLE001 - client construction is a protocol call
            raise _translate(exc) from exc

    @staticmethod
    def _type_dir(ov_user: str, memory_type: str) -> str:
        return f"viking://user/{ov_user}/{_MEMORY_ROOT}/{memory_type}"


def _content(uri: str, content: str) -> MemoryContent:
    return MemoryContent(
        uri=uri,
        content=content,
        sha256=_sha256(content),
        size_bytes=len(content.encode("utf-8")),
    )


def _sha256(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _translate(exc: Exception) -> Exception:
    code = str(getattr(exc, "code", "") or type(exc).__name__).upper()
    name = type(exc).__name__.upper()
    if "NOT_FOUND" in code or "NOT_FOUND" in name:
        return MemoryItemNotFound(str(exc))
    if "INVALID_ARGUMENT" in code or "INVALIDARGUMENT" in name:
        return MemoryItemNotFound("memory file not found or not a file")
    if "PERMISSION" in code or "PERMISSIONDENIED" in name:
        return MemoryUnavailable("permission denied by OpenViking")
    return MemoryUnavailable(f"OpenViking memory call failed: {type(exc).__name__}")


