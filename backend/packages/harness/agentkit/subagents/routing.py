"""委派措辞的唯一来源（M8 §1 / §18）。

三处各管一件事，不要互相抄：

1. 各类型的 ``description``：什么时候值得派给它（收益 / 否决 / 成本），由 lead 在委派段里读到；
2. ``task`` 工具的描述：工具契约（子代理看得到什么、结果怎么回来、失败怎么处理）；
3. lead 委派段：可用类型名单、并行限额与本 run 的委派总量。

真正想否决的只有两条：**输出依赖**与**可变状态重叠**，而且只针对**同一轮并行**——串行委派时，
前一个的结论可以直接写进后一个的任务说明。重新了解情况、多一轮综合是**成本**，要权衡，
但不是"不许派"。

``max_concurrent == 1`` 时提示词里不许出现并行字样：提示词教模型并行、中间件却只放行 1 个，
模型会空转。所以每个常量都是**完整的一句话**，按策略整句取舍，不嵌进别的句子中间。

本模块只放字符串常量：不要在这里 import 任何东西，免得把提示词变成一张隐藏的依赖图。
"""

